using Microsoft.Extensions.Logging.Abstractions;
using Moq;
using NightCodeForge.Core.Domain;
using NightCodeForge.Core.Execution;
using NightCodeForge.Core.Interfaces;
using NightCodeForge.Infrastructure.Execution;
using NightCodeForge.Infrastructure.Git;

namespace NightCodeForge.Infrastructure.Tests.Git;

public class NoiseFilteredDiffTests : IDisposable
{
    private readonly TestGitRepository _repo;
    private readonly GitCliRunner _runner;
    private readonly GitWorkspaceManager _manager;
    private readonly Workspace _workspace;

    public NoiseFilteredDiffTests()
    {
        var wslMeta = new Mock<IWslMetadataService>().Object;
        var pathResolver = new WorkspacePathResolver(wslMeta, Microsoft.Extensions.Options.Options.Create(new ExecutionEnvironmentProviderOptions()));
        _repo = new TestGitRepository("main");
        _runner = new GitCliRunner(
            new SystemProcessRunner(NullLogger<SystemProcessRunner>.Instance),
            pathResolver,
            wslMeta,
            NullLogger<GitCliRunner>.Instance);
        _manager = new GitWorkspaceManager(
            _runner,
            pathResolver,
            wslMeta,
            new Mock<IGitMirrorSyncService>().Object,
            new Mock<IWorkspaceLockProvider>().Object,
            NullLogger<GitWorkspaceManager>.Instance);

        // Base branch setup
        _repo.CreateFile("README.md", "# Base Project");
        _repo.CommitAll("Initial commit");

        _workspace = new Workspace
        {
            Id = 50,
            Name = "Diff Workspace",
            RepositoryPath = _repo.RepositoryPath,
            DefaultBaseBranch = "main"
        };
    }

    [Fact]
    public async Task GenerateDiffAsync_IncludesSourceChanges_AndFiltersOutNoisyArtifacts()
    {
        // Arrange
        await _manager.CheckoutTaskBranchAsync(_workspace, 201, "main");
        var wtPath = _manager.GetWorktreePath(_workspace, 201);

        // 1. Legitimate source code change
        _repo.CreateFile("src/Services/PaymentService.cs",
            "public class PaymentService\n{\n    public void Process() { }\n}\n", wtPath);

        // 2. Noisy lockfiles and generated code
        _repo.CreateFile("package-lock.json", "{\"name\": \"heavy-lockfile\", \"version\": \"1.0.0\"}", wtPath);
        _repo.CreateFile("pnpm-lock.yaml", "lockfileVersion: 5.4\nspecifiers:\n  lodash: 4.17.21", wtPath);
        _repo.CreateFile("yarn.lock", "# yarn lockfile v1\nlodash@^4.17.21:\n  version \"4.17.21\"", wtPath);
        _repo.CreateFile("Views/Form1.Designer.cs", "// <auto-generated>\npartial class Form1 {}", wtPath);
        _repo.CreateFile("CodeGen.generated.cs", "// <auto-generated>\npublic class GeneratedTypes {}", wtPath);

        // Commit all changes on the task branch
        await _manager.CreateWipCheckpointAsync(_workspace, 201, "Implementation", "Added PaymentService and dependencies");

        // Act
        var diff = await _manager.GenerateDiffAsync(_workspace, 201, "main");

        // Assert: Legitimate source code changes MUST be present
        Assert.Contains("src/Services/PaymentService.cs", diff);
        Assert.Contains("+public class PaymentService", diff);

        // Assert: Noisy lockfiles and generated files MUST be excluded
        Assert.DoesNotContain("package-lock.json", diff);
        Assert.DoesNotContain("pnpm-lock.yaml", diff);
        Assert.DoesNotContain("yarn.lock", diff);
        Assert.DoesNotContain("Form1.Designer.cs", diff);
        Assert.DoesNotContain("CodeGen.generated.cs", diff);
    }

    [Fact]
    public async Task GenerateDiffAsync_EnforcesU2ContextWindow()
    {
        // Arrange: Multi-line file on main
        var initialLines = string.Join("\n", Enumerable.Range(1, 20).Select(i => $"Line {i}"));
        _repo.CreateFile("src/Document.txt", initialLines);
        _repo.CommitAll("Add document");

        await _manager.CheckoutTaskBranchAsync(_workspace, 202, "main");
        var wtPath = _manager.GetWorktreePath(_workspace, 202);

        // Modify only Line 10
        var modifiedLines = initialLines.Replace("Line 10", "Line 10 [MODIFIED]");
        _repo.CreateFile("src/Document.txt", modifiedLines, wtPath);
        await _manager.CreateWipCheckpointAsync(_workspace, 202, "Implementation", "Modified line 10");

        // Act
        var diff = await _manager.GenerateDiffAsync(_workspace, 202, "main");

        // Assert: -U2 provides 2 lines of context around line 10 (Line 8, 9 and Line 11, 12)
        Assert.Contains("+Line 10 [MODIFIED]", diff);
        Assert.Contains("Line 8", diff);
        Assert.Contains("Line 9", diff);
        Assert.Contains("Line 11", diff);
        Assert.Contains("Line 12", diff);

        // But Line 5 (further out) should not appear in a -U2 hunk
        Assert.DoesNotContain("Line 5", diff);
        Assert.DoesNotContain("Line 16", diff);
    }

    public void Dispose()
    {
        _repo.Dispose();
    }
}
