using NightCodeForge.Core.Domain;
using NightCodeForge.Core.Services;

namespace NightCodeForge.Web.Services;

/// <summary>
/// Executive summary extracted from transcript YAML frontmatter and file metadata.
/// </summary>
public record TranscriptSummary(
    string FileName,
    string FilePath,
    int TaskId,
    string StageId,
    string ModelName,
    DateTime Timestamp,
    int PromptTokens,
    int CompletionTokens,
    int DurationMs,
    string Status,
    string? AgentProfile = null,
    double? KvCacheHitRate = null,
    LocalOptimizationFlags? Optimizations = null,
    bool HasFriction = false,
    int TotalErrors = 0)
{
    public int TotalTokens => PromptTokens + CompletionTokens;
}

/// <summary>
/// Structured post-mortem diagnostic report generated by AI or rule-based heuristics.
/// </summary>
public record DiagnosticReport(
    string RootCause,
    string FailureCategory,
    IReadOnlyList<string> CritiquePoints,
    IReadOnlyList<RemediationSuggestion> SuggestedActions,
    string? FullMarkdownReport = null);

/// <summary>
/// Concrete remediation action that can be applied to workspace or agent profile settings.
/// </summary>
public record RemediationSuggestion(
    string Title,
    string Description,
    string ActionType, // e.g., "ToggleOptimizationFlag", "UpdatePrompt"
    string? TargetKey,
    object? TargetValue);

/// <summary>
/// A turn or event extracted from an execution transcript.
/// </summary>
public record ParsedTranscriptTurn(
    string Offset,
    string Role,
    string Content,
    string? ThinkingTrace = null,
    string? ToolName = null,
    string? ToolArguments = null,
    string? ToolResult = null,
    bool IsTool = false,
    bool IsError = false);

/// <summary>
/// Detailed breakdown of a transcript file including turns, environment, and model call snapshots.
/// </summary>
public record ParsedTranscriptDetail(
    TranscriptSummary Metadata,
    string RawMarkdown,
    string? SystemPrompt,
    IReadOnlyList<string> AvailableTools,
    IReadOnlyList<string> ActiveSkills,
    IReadOnlyList<ParsedTranscriptTurn> Turns,
    string? ModelCallsMarkdown = null,
    TranscriptAnalysis? Analysis = null);
