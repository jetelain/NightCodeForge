namespace NightCodeForge.Core.Resilience;

using System.Net.Http;
using System.Text.Json;

/// <summary>
/// Utility helper for extracting and formatting detailed error messages and JSON payloads from HTTP error responses
/// (such as Ollama or OllamaRouter error responses).
/// </summary>
public static class HttpErrorDetailHelper
{
    public const string ResponseBodyKey = "ResponseBody";
    public const int MaxRawErrorBodyLength = 500;
    public const int DefaultMaxReasonPhraseLength = 200;

    private static readonly string[] RecognizedLlmExceptionTypeSubstrings =
    [
        "OllamaException",
        "ResponseError",
        "ModelDoesNotSupportToolsException"
    ];

    /// <summary>
    /// Attempts to extract a concise error message from an HTTP response body (e.g. Ollama or OllamaRouter error payload).
    /// </summary>
    public static string? ExtractErrorMessageFromBody(string? body)
    {
        if (string.IsNullOrWhiteSpace(body))
        {
            return null;
        }

        try
        {
            using var doc = JsonDocument.Parse(body);
            if (doc.RootElement.ValueKind == JsonValueKind.Object)
            {
                if (doc.RootElement.TryGetProperty("error", out var errorProp))
                {
                    if (errorProp.ValueKind == JsonValueKind.String)
                    {
                        var str = errorProp.GetString();
                        if (!string.IsNullOrWhiteSpace(str)) return str.Trim();
                    }
                    else if (errorProp.ValueKind == JsonValueKind.Object && errorProp.TryGetProperty("message", out var msgProp) && msgProp.ValueKind == JsonValueKind.String)
                    {
                        var str = msgProp.GetString();
                        if (!string.IsNullOrWhiteSpace(str)) return str.Trim();
                    }
                }

                if (doc.RootElement.TryGetProperty("message", out var messageProp) && messageProp.ValueKind == JsonValueKind.String)
                {
                    var str = messageProp.GetString();
                    if (!string.IsNullOrWhiteSpace(str)) return str.Trim();
                }

                if (doc.RootElement.TryGetProperty("detail", out var detailProp) && detailProp.ValueKind == JsonValueKind.String)
                {
                    var str = detailProp.GetString();
                    if (!string.IsNullOrWhiteSpace(str)) return str.Trim();
                }
            }
        }
        catch (JsonException)
        {
            // Justification: Non-JSON plain text body; fall back to raw text.
        }

        var trimmed = body.Trim();
        return trimmed.Length <= MaxRawErrorBodyLength ? trimmed : trimmed[..MaxRawErrorBodyLength] + "...";
    }

    /// <summary>
    /// Extracts enriched detail from an HttpRequestException message if it contains an enriched ReasonPhrase
    /// (e.g. "Response status code does not indicate success: 503 (Service Unavailable: No enabled routing target...)").
    /// </summary>
    public static string? ExtractErrorMessageFromHttpExceptionMessage(string? message)
    {
        if (string.IsNullOrWhiteSpace(message)) return null;

        // Ensure this is an HTTP non-success exception message generated by EnsureSuccessStatusCode()
        if (!message.Contains("Response status code does not indicate success", StringComparison.OrdinalIgnoreCase))
        {
            return null;
        }

        var openParen = message.IndexOf('(');
        var closeParen = message.LastIndexOf(')');
        if (openParen >= 0 && closeParen > openParen)
        {
            var inside = message.Substring(openParen + 1, closeParen - openParen - 1).Trim();
            var colonIdx = inside.IndexOf(':');
            if (colonIdx >= 0 && colonIdx < inside.Length - 1)
            {
                var candidate = inside[(colonIdx + 1)..].Trim();
                if (!string.IsNullOrWhiteSpace(candidate))
                {
                    return candidate;
                }
            }
        }

        return null;
    }

    /// <summary>
    /// Formats an exception thrown by an LLM or inference client invocation into a descriptive, actionable message.
    /// Extracts response bodies from HttpRequestException and error strings from OllamaSharp exceptions.
    /// 100% fail-safe: never throws, returning ex.Message (or string.Empty if null) if parsing fails.
    /// </summary>
    public static string FormatLlmInvocationError(Exception? ex)
    {
        if (ex == null)
        {
            return string.Empty;
        }

        try
        {
            // Find HttpRequestException in exception chain
            var httpEx = FindException<HttpRequestException>(ex);
            if (httpEx != null)
            {
                string? cleanDetail = null;

                // 1. Explicit body attached directly to exception instance
                if (httpEx.Data.Contains(ResponseBodyKey) && httpEx.Data[ResponseBodyKey] is string dataBody && !string.IsNullOrWhiteSpace(dataBody))
                {
                    cleanDetail = ExtractErrorMessageFromBody(dataBody);
                }

                // 2. Enriched ReasonPhrase embedded directly in this exception's message (immune to concurrency cross-talk)
                if (string.IsNullOrWhiteSpace(cleanDetail) && !string.IsNullOrWhiteSpace(httpEx.Message))
                {
                    cleanDetail = ExtractErrorMessageFromHttpExceptionMessage(httpEx.Message);
                }

                if (!string.IsNullOrWhiteSpace(cleanDetail))
                {
                    return httpEx.StatusCode.HasValue
                        ? $"HTTP {(int)httpEx.StatusCode.Value} ({httpEx.StatusCode.Value}): {cleanDetail}"
                        : cleanDetail;
                }
            }

            // Check if any exception in the chain provides a distinct message (e.g. OllamaException)
            var recognizedEx = FindRecognizedLlmException(ex);
            if (recognizedEx != null && !string.IsNullOrWhiteSpace(recognizedEx.Message))
            {
                return recognizedEx.Message;
            }

            return ex.InnerException != null ? $"{ex.Message} (Inner: {ex.InnerException.Message})" : ex.Message;
        }
        catch (Exception)
        {
            // Justification: FormatLlmInvocationError must be 100% fail-safe so error formatting never disrupts exception handling, harness failure, or telemetry.
            return ex.Message;
        }
    }

    private static Exception? FindRecognizedLlmException(Exception? ex)
    {
        while (ex != null)
        {
            var typeName = ex.GetType().Name;
            if (RecognizedLlmExceptionTypeSubstrings.Any(sub => typeName.Contains(sub, StringComparison.OrdinalIgnoreCase)))
            {
                if (!string.IsNullOrWhiteSpace(ex.Message))
                {
                    return ex;
                }
            }

            if (ex is AggregateException agg)
            {
                foreach (var inner in agg.InnerExceptions)
                {
                    var match = FindRecognizedLlmException(inner);
                    if (match != null) return match;
                }
            }

            ex = ex.InnerException;
        }

        return null;
    }

    public static T? FindException<T>(Exception? ex) where T : Exception
    {
        while (ex != null)
        {
            if (ex is T match)
            {
                return match;
            }

            if (ex is AggregateException agg)
            {
                foreach (var inner in agg.InnerExceptions)
                {
                    var found = FindException<T>(inner);
                    if (found != null)
                    {
                        return found;
                    }
                }

                return null;
            }

            ex = ex.InnerException;
        }

        return null;
    }

    public static string SanitizeForReasonPhrase(string text, int maxLength = DefaultMaxReasonPhraseLength)
    {
        if (string.IsNullOrWhiteSpace(text)) return string.Empty;
        var sanitized = new string(text.Select(c => char.IsControl(c) ? ' ' : c).ToArray()).Trim();
        if (sanitized.Length > maxLength)
        {
            sanitized = sanitized[..maxLength] + "...";
        }
        return sanitized;
    }
}
